const ENTRIES = Object.entries(RULES).flatMap(([cat, kws]) => kws.map((kw) => ({ cat, kw, anchored: kw.startsWith('^'), word: kw.replace(/^\^/u, '') })));

// 가장 긴 키워드가 이깁니다("쿠팡" < "쿠팡와우", "쿠팡이츠" → 식비로 구분).
export function matchRule(norm) {
  let best = null;
  for (const e of ENTRIES) {
    const hit = e.anchored ? norm.startsWith(e.word) : norm.includes(e.word);
    if (hit && (!best || e.word.length > best.word.length)) best = e;
  }
  return best;
}

// userRules: Map(가맹점 키 → 카테고리). 반환: { category, method: 'user'|'rule'|'none', keyword }
export function classify(norm, userRules) {
  const u = userRules?.get(norm);
  if (u) return { category: u, method: 'user', keyword: null };
  const r = matchRule(norm);
  if (r) return { category: r.cat, method: 'rule', keyword: r.word };
  return { category: '기타', method: 'none', keyword: null };
}
