const GATEWAY = /^(?:카카오페이|네이버페이|naverpay|토스페이|토스|kbpay|삼성페이|페이코|payco|스마일페이|smilepay)(?:[*_]|\s+)/u;

// 표기 차이를 없앤 "가맹점 키": 소문자·결제대행 접두어·(주)·지점명·끝 번호·공백·특수문자 제거
export function normalizeMerchant(raw) {
  let s = String(raw ?? '').normalize('NFKC').toLowerCase();
  s = s.replace(/\(주\)|㈜|주식회사|\(유\)|유한회사/gu, ' ');
  s = s.replace(GATEWAY, '');
  s = s.replace(/[^\p{L}\p{N}\s&+]/gu, ' ').replace(/\s+/gu, ' ').trim();
  s = s.replace(/\s+\S{1,7}(?:지점|호점|점)$/u, '');          // "스타벅스 강남역점" → "스타벅스"
  s = s.replace(/(?<=[a-z0-9])[가-힣]{1,4}점$/u, '');          // "gs25강남점" → "gs25"
  s = s.replace(/\s+#?\d{2,}$/u, '');                          // 끝에 붙은 번호
  return s.replace(/\s+/gu, '') || String(raw ?? '').trim().toLowerCase().slice(0, 30) || '(내용없음)';
}

